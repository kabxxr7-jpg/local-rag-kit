"""Turns a scenario run into docs/scenarios/*.md and docs/SCENARIOS.md. Only a run against the real Ollama is recorded."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "scenarios"


def _fence(text: str) -> str:
    text = text.strip("\n") or "(no output)"
    return "```text\n" + text + "\n```\n"


def _ops(phase) -> str:
    lines = []
    for op, out in phase.ops:
        lines.append(op.describe())
    return "```text\n" + "\n".join(lines) + "\n```\n"


def write_reports(outcomes, backend: str) -> None:
    if backend != "ollama":
        print("not recorded: only a run against the real Ollama is written to docs/ (use --backend ollama --record)")
        return
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.md"):
        old.unlink()
    rows = []
    for n, o in enumerate((x for x in outcomes if not x.skipped), start=1):
        s = o.scenario
        refused = sum(1 for p in o.wrongs.values() if p.passed is False)
        passing = sum(1 for p in o.fixes.values() if p.passed)
        md = [f"# {n:02d}. {s.title}", "", f"`{s.name}`  |  run against: real Ollama (nomic-embed-text, llama3.2:1b)  |  result: **{'OK' if o.ok else 'PROBLEM'}**", "", s.story, ""]
        md += ["## Symptom (real output, broken state)", ""]
        for cmd, out in o.symptom:
            md += [_fence(cmd + "\n" + out)]
        md += ["## Diagnosis", ""]
        for cmd, out in o.diagnose:
            md += [_fence(cmd + "\n" + out)]
        md += ["## The check", "", f"The same check runs after every change. It decides; nothing else does.", "", f"Healthy state (control): **{'passes' if o.control.passed else 'FAILS'}**", "", _fence(o.control.check_output), f"Broken state: **{'fails' if o.broken.passed is False else 'PASSES'}**", "", _fence(o.broken.check_output)]
        if o.broken.observed:
            md += ["Not part of the verdict, what the user would see in the broken state:", ""]
            for cmd, out in o.broken.observed:
                md += [_fence(cmd + "\n" + out)]
        md += ["## Fixes that pass the check", ""]
        for name, ph in o.fixes.items():
            md += [f"### `{name}`: {'passes' if ph.passed else 'FAILS'}", "", s.fix_notes.get(name, ""), "", "What changes:", "", _ops(ph), _fence(ph.check_output)]
            if ph.observed:
                md += ["Not part of the verdict, what the user sees now:", ""]
                for cmd, out in ph.observed:
                    md += [_fence(cmd + "\n" + out)]
        md += ["## Wrong fixes the check refuses", ""]
        for name, ph in o.wrongs.items():
            md += [f"### `{name}`: {'refused' if ph.passed is False else 'ACCEPTED'}", "", s.wrong_notes.get(name, ""), "", "What changes:", "", _ops(ph), "The check says:", "", _fence(ph.check_output)]
        (OUT / f"{n:02d}-{s.name}.md").write_text("\n".join(md) + "\n", encoding="utf-8")
        first_fail = next((l for l in o.broken.check_output.splitlines() if l.startswith("FAIL")), "").replace("FAIL  ", "")
        rows.append((n, s, o, passing, refused, first_fail))
    table = ["# Scenarios: fixing an inherited pipeline", "",
             "Generated by `python scenarios/run.py --backend ollama --record` against the real Ollama (nomic-embed-text, llama3.2:1b). Each file below has the real output of the broken state, the diagnosis, the fix and the wrong fixes.", "",
             "| # | Scenario | First thing the check says on the broken state | Fixes that pass | Wrong fixes refused |", "|---|---|---|---|---|"]
    for n, s, o, passing, refused, first_fail in rows:
        table.append(f"| {n:02d} | [{s.title}]({'scenarios/%02d-%s.md' % (n, s.name)}) | {first_fail.replace('|', '/')[:150]} | {passing}/{len(o.fixes)} | {refused}/{len(o.wrongs)} |")
    total_fix = sum(len(o.fixes) for _, _, o, _, _, _ in rows)
    total_wrong = sum(len(o.wrongs) for _, _, o, _, _, _ in rows)
    table += ["", f"**{sum(p for _, _, _, p, _, _ in rows)} of {total_fix} fixes pass the check; {sum(r for _, _, _, _, r, _ in rows)} of {total_wrong} wrong fixes are refused.**", ""]
    (ROOT / "docs" / "SCENARIOS.md").write_text("\n".join(table) + "\n", encoding="utf-8")
    (OUT / "results.json").write_text(json.dumps([{"scenario": o.scenario.name, "ok": o.ok, "control_passes": o.control.passed, "broken_fails": o.broken.passed is False, "fixes": {k: v.passed for k, v in o.fixes.items()}, "wrongs_refused": {k: v.passed is False for k, v in o.wrongs.items()}} for o in outcomes if not o.skipped], indent=1), encoding="utf-8")
    print(f"recorded {len(rows)} scenarios in docs/scenarios and docs/SCENARIOS.md")
